void drawMainMenu(void){
    for(uint8_t i = 0; i < 8; ++i){
        lcd_busyWait();
        lcd_setPageAddr(7-i);
        lcd_setColumnAddr(40);
        for(uint8_t j = 0; j < 19; ++j){
            lcd_data = TETRIS[j][i];
        }
        lcd_busyWait();
        lcd_setColumnAddr(70);
        for(uint8_t j = 0; j < 8; ++j){
            lcd_data = PRESS[j][i];
        }
        lcd_busyWait();
        lcd_setColumnAddr(128-44);
        for(uint8_t j = 0; j < 44; ++j){
            lcd_data = menu_art[j][i];
        }
        if(i >= 3){
            lcd_busyWait();
            lcd_setColumnAddr(2);
            for(uint8_t j = 0; j < 11; ++j){
                lcd_data = muteInfo[j][i-3];
            }
        }
    }
}

void drawPressStart(uint8_t offsetY){
    for(uint8_t i = 0; i < 8; ++i){
        lcd_busyWait();
        lcd_setPageAddr(7-i);
        lcd_setColumnAddr(offsetY);
        for(uint8_t j = 0; j < 8; ++j){
            lcd_data = PRESS[j][i];
        }
    }
}